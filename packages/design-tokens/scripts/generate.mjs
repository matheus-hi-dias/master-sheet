import {
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  auraGradient,
  colorTokens,
  fontAssets,
  motion,
  radii,
  shadows,
  spacing,
  typography,
} from '../dist/tokens.js';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const workspaceRoot = resolve(packageRoot, '../..');
const generatedDir = join(packageRoot, 'generated');
const fontsDir = join(packageRoot, 'fonts');
const webFontsDir = join(workspaceRoot, 'apps', 'web', 'public', 'fonts');

const HEADER = [
  '/* AUTO-GENERATED by packages/design-tokens/scripts/generate.mjs.',
  ' * Edit packages/design-tokens/src/tokens.ts and run `pnpm tokens:generate`.',
  ' */',
  '',
].join('\n');

const TS_HEADER = [
  '// AUTO-GENERATED by packages/design-tokens/scripts/generate.mjs.',
  '// Edit packages/design-tokens/src/tokens.ts and run `pnpm tokens:generate`.',
  '',
].join('\n');

function kebabCase(value) {
  return value.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
}

function themeColors() {
  const dark = {};
  const light = {};

  for (const [name, value] of Object.entries(colorTokens)) {
    dark[name] = value.dark;
    light[name] = value.light;
  }

  return { dark, light };
}

function themeShadows() {
  const dark = {};
  const light = {};

  for (const [name, value] of Object.entries(shadows)) {
    dark[name] = value.dark;
    light[name] = value.light;
  }

  return { dark, light };
}

function cssVariables(theme, options = {}) {
  const lines = [];

  for (const [name, value] of Object.entries(theme.colors)) {
    lines.push(`  --color-${kebabCase(name)}: ${value};`);
  }

  for (const [name, value] of Object.entries(theme.shadows)) {
    lines.push(`  --shadow-${kebabCase(name)}: ${value};`);
  }

  for (const [name, value] of Object.entries(radii)) {
    lines.push(`  --radius-${kebabCase(name)}: ${value};`);
  }

  for (const [name, value] of Object.entries(spacing)) {
    // Keep spacing outside Tailwind's `--spacing-*` namespace: names such as
    // `sm`/`md`/`lg` would otherwise shadow the `max-w-*` container scale
    // (for example `max-w-sm` would resolve to 8px instead of 24rem).
    lines.push(`  --space-${kebabCase(name)}: ${value};`);
  }

  for (const [name, value] of Object.entries(motion.duration)) {
    lines.push(`  --motion-duration-${kebabCase(name)}: ${value}ms;`);
  }

  for (const [name, value] of Object.entries(motion.easing)) {
    lines.push(`  --motion-easing-${kebabCase(name)}: ${value};`);
  }

  if (options.includeFonts) {
    lines.push(`  --font-display: ${typography.display.webStack};`);
    lines.push(`  --font-body: ${typography.body.webStack};`);
    lines.push(`  --background-image-aura: ${auraGradient};`);
  }

  return lines;
}

function buildTokensCss() {
  const colors = themeColors();
  const shadowValues = themeShadows();

  const rootLines = cssVariables(
    { colors: colors.dark, shadows: shadowValues.dark },
    { includeFonts: true },
  );
  const lightLines = cssVariables({
    colors: colors.light,
    shadows: shadowValues.light,
  });

  return `${HEADER}:root {
${rootLines.join('\n')}
}

.light {
${lightLines.join('\n')}
}
`;
}

function buildWebThemeCss() {
  const colors = themeColors();
  const shadowValues = themeShadows();

  const themeLines = cssVariables(
    { colors: colors.dark, shadows: shadowValues.dark },
    { includeFonts: true },
  );

  const lightLines = [];
  for (const [name, value] of Object.entries(colors.light)) {
    if (value !== colors.dark[name]) {
      lightLines.push(`    --color-${kebabCase(name)}: ${value};`);
    }
  }
  for (const [name, value] of Object.entries(shadowValues.light)) {
    if (value !== shadowValues.dark[name]) {
      lightLines.push(`    --shadow-${kebabCase(name)}: ${value};`);
    }
  }

  return `${HEADER}@theme static {
${themeLines.join('\n')}
}

@layer base {
  :root.light {
${lightLines.join('\n')}
  }
}
`;
}

function buildFontsCss() {
  const blocks = fontAssets.map((font) => {
    return `@font-face {
  font-family: '${font.family}';
  src: url('/fonts/${font.file}') format('truetype');
  font-weight: ${font.weight};
  font-style: ${font.style};
  font-display: swap;
}`;
  });

  return `${HEADER}${blocks.join('\n\n')}\n`;
}

function buildTokensTs() {
  const colors = themeColors();
  const shadowValues = themeShadows();

  return `${TS_HEADER}export const colorTokens = ${JSON.stringify(
    colors,
    null,
    2,
  )} as const;

export type ThemeName = keyof typeof colorTokens;
export type ColorName = keyof (typeof colorTokens)['dark'];

export const shadows = ${JSON.stringify(
    shadowValues,
    null,
    2,
  )} as const;

export type ShadowName = keyof (typeof shadows)['dark'];

export const radii = ${JSON.stringify(radii, null, 2)} as const;

export const spacing = ${JSON.stringify(spacing, null, 2)} as const;

export const typography = ${JSON.stringify(typography, null, 2)} as const;

export const motion = ${JSON.stringify(motion, null, 2)} as const;

export const auraGradient = ${JSON.stringify(auraGradient)};

export const fontAssets = ${JSON.stringify(fontAssets, null, 2)} as const;
`;
}

function buildTailwindPreset() {
  const preset = {
    theme: {
      extend: {
        colors: {
          bg: {
            app: 'var(--color-bg-app)',
            panel: 'var(--color-bg-panel)',
            card: 'var(--color-bg-card)',
          },
          text: {
            main: 'var(--color-text-main)',
            muted: 'var(--color-text-muted)',
          },
          gold: {
            DEFAULT: 'var(--color-gold)',
            dim: 'var(--color-gold-dim)',
            tint: 'var(--color-gold-tint)',
          },
          border: 'var(--color-border)',
          danger: 'var(--color-danger)',
          dangerTint: 'var(--color-danger-tint)',
          success: 'var(--color-success)',
          warning: 'var(--color-warning)',
          link: 'var(--color-link)',
          onGold: 'var(--color-on-gold)',
        },
        fontFamily: {
          display: [typography.display.family],
          body: [typography.body.family],
        },
        borderRadius: {
          card: radii.card,
          pill: radii.pill,
        },
      },
    },
  };

  return `${HEADER}module.exports = ${JSON.stringify(preset, null, 2)};\n`;
}

function buildFontManifest() {
  const imports = fontAssets
    .map(
      (font, index) =>
        `import font${index} from '../fonts/${font.file}';`,
    )
    .join('\n');
  const entries = fontAssets
    .map(
      (font, index) =>
        `  ${JSON.stringify(font.family)}: font${index},`,
    )
    .join('\n');
  const families = fontAssets
    .map(
      (font) =>
        `  ${JSON.stringify(font.family)}: ${JSON.stringify({
          weight: font.weight,
          style: font.style,
          file: font.file,
        })},`,
    )
    .join('\n');

  return `${HEADER}${imports}

export const fontAssets = {
${entries}
};

export const fontFamilies = {
${families}
};
`;
}

function buildFontManifestTypes() {
  return `${TS_HEADER}export declare const fontAssets: Record<string, number>;

export declare const fontFamilies: Record<
  string,
  { weight: string; style: string; file: string }
>;
`;
}

function buildTokensJson() {
  const colors = themeColors();
  const shadowValues = themeShadows();

  return `${JSON.stringify(
    {
      colors,
      radii,
      spacing,
      typography,
      shadows: shadowValues,
      motion,
      auraGradient,
      fonts: fontAssets,
    },
    null,
    2,
  )}\n`;
}

export function buildArtifacts() {
  const artifacts = new Map();

  artifacts.set(join(generatedDir, 'tokens.ts'), buildTokensTs());
  artifacts.set(join(generatedDir, 'tokens.css'), buildTokensCss());
  artifacts.set(join(generatedDir, 'web-theme.css'), buildWebThemeCss());
  artifacts.set(join(generatedDir, 'fonts.css'), buildFontsCss());
  artifacts.set(join(generatedDir, 'tailwind-preset.cjs'), buildTailwindPreset());
  artifacts.set(join(generatedDir, 'font-manifest.js'), buildFontManifest());
  artifacts.set(
    join(generatedDir, 'font-manifest.d.ts'),
    buildFontManifestTypes(),
  );
  artifacts.set(join(generatedDir, 'tokens.json'), buildTokensJson());

  for (const font of fontAssets) {
    const source = join(fontsDir, font.file);

    if (!existsSync(source)) {
      throw new Error(`Missing shared font asset: ${source}`);
    }

    artifacts.set(join(webFontsDir, font.file), readFileSync(source));
  }

  return artifacts;
}

function writeArtifacts(artifacts) {
  for (const [path, content] of artifacts) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
}

export function checkArtifacts(artifacts) {
  const stale = [];

  for (const [path, expected] of artifacts) {
    if (!existsSync(path)) {
      stale.push(`${path} (missing)`);
      continue;
    }

    const actual = readFileSync(path);
    const expectedBuffer = Buffer.isBuffer(expected)
      ? expected
      : Buffer.from(expected);

    if (!actual.equals(expectedBuffer)) {
      stale.push(path);
    }
  }

  return stale;
}

function main() {
  const check = process.argv.includes('--check');
  const artifacts = buildArtifacts();

  if (check) {
    const stale = checkArtifacts(artifacts);

    if (stale.length > 0) {
      console.error('Generated design-token artifacts are stale:');

      for (const path of stale) {
        console.error(`  - ${path}`);
      }

      console.error('Run `pnpm tokens:generate` and commit the result.');
      process.exitCode = 1;
      return;
    }

    console.log(`Design-token artifacts are fresh (${artifacts.size} files).`);
    return;
  }

  writeArtifacts(artifacts);
  console.log(`Generated ${artifacts.size} design-token artifacts.`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
